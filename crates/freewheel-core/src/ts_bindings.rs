//! ADR-15: the settings window's TypeScript types are generated from the
//! serde types with ts-rs, and this test fails when `src/bindings.ts` drifts
//! from them. Regenerate with
//! `FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings`.

use std::path::PathBuf;

use ts_rs::TS;

use crate::battery::Battery;
use crate::config::{
    Action, Appearance, Config, JogBinding, JogMode, JogSettings, KeyCombo, Layer, Modifier,
    OverrideMode, OverrideSettings, PerOsTargets, Profile, ProfileApp, SaveError, Settings,
};
use crate::connection::ConnectionStatus;
use crate::diagnostics::{
    AuthDiagnostics, AuthState, DeviceDiagnostics, DeviceInfo, Direction, RawReport,
    WheelDiagnostics,
};
use crate::permissions::Grant;
use crate::simulator::Bus;
use crate::status::{KeyPressed, OverrideErrorStatus, StatusEvent};

const HEADER: &str = "// Generated by ts-rs from the Rust serde types in crates/freewheel-core.\n\
// Do not edit: run `FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings`.\n";

fn generated() -> String {
    // Defaults, not `Config::from_env()`: the output must not depend on TS_RS_* in the environment.
    let cfg = ts_rs::Config::new();
    let decls = [
        Config::decl(&cfg),
        Settings::decl(&cfg),
        Appearance::decl(&cfg),
        Layer::decl(&cfg),
        Profile::decl(&cfg),
        ProfileApp::decl(&cfg),
        Action::decl(&cfg),
        PerOsTargets::decl(&cfg),
        KeyCombo::decl(&cfg),
        Modifier::decl(&cfg),
        JogMode::decl(&cfg),
        OverrideMode::decl(&cfg),
        JogSettings::decl(&cfg),
        JogBinding::decl(&cfg),
        OverrideSettings::decl(&cfg),
        SaveError::decl(&cfg),
        StatusEvent::decl(&cfg),
        ConnectionStatus::decl(&cfg),
        Battery::decl(&cfg),
        OverrideErrorStatus::decl(&cfg),
        Grant::decl(&cfg),
        KeyPressed::decl(&cfg),
        Bus::decl(&cfg),
        DeviceDiagnostics::decl(&cfg),
        DeviceInfo::decl(&cfg),
        AuthDiagnostics::decl(&cfg),
        AuthState::decl(&cfg),
        WheelDiagnostics::decl(&cfg),
        RawReport::decl(&cfg),
        Direction::decl(&cfg),
    ];
    let mut out = String::from(HEADER);
    for decl in decls {
        out.push_str("\nexport ");
        out.push_str(&decl);
        out.push('\n');
    }
    out
}

fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/bindings.ts")
}

#[test]
fn ts_bindings_match_the_rust_types() {
    let want = generated();
    if std::env::var_os("FREEWHEEL_WRITE_TS").is_some() {
        std::fs::write(bindings_path(), &want).unwrap();
    }
    let have = std::fs::read_to_string(bindings_path()).unwrap_or_default();
    assert!(
        have == want,
        "src/bindings.ts drifted from the Rust types; regenerate it with \
         FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings\n{want}"
    );
}
