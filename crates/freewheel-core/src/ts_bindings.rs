//! ADR-15: the settings window's TypeScript types are generated from the
//! serde types with ts-rs, and this test fails when `src/bindings.ts` drifts
//! from them. Regenerate with
//! `FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings`.

use std::path::PathBuf;

use ts_rs::TS;

use crate::battery::Battery;
use crate::config::{
    Action, Config, JogBinding, JogMode, JogSettings, KeyCombo, Layer, Modifier, OverrideMode,
    OverrideSettings, SaveError, Settings,
};
use crate::connection::ConnectionStatus;
use crate::permissions::Grant;
use crate::status::{KeyPressed, OverrideErrorStatus, StatusEvent};

const HEADER: &str = "// Generated by ts-rs from the Rust serde types in crates/freewheel-core.\n\
// Do not edit: run `FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings`.\n";

fn generated() -> String {
    let decls = [
        Config::decl(),
        Settings::decl(),
        Layer::decl(),
        Action::decl(),
        KeyCombo::decl(),
        Modifier::decl(),
        JogMode::decl(),
        OverrideMode::decl(),
        JogSettings::decl(),
        JogBinding::decl(),
        OverrideSettings::decl(),
        SaveError::decl(),
        StatusEvent::decl(),
        ConnectionStatus::decl(),
        Battery::decl(),
        OverrideErrorStatus::decl(),
        Grant::decl(),
        KeyPressed::decl(),
    ];
    let mut out = String::from(HEADER);
    for decl in decls {
        out.push_str("\nexport ");
        out.push_str(&decl);
        out.push('\n');
    }
    out
}

fn bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/bindings.ts")
}

#[test]
fn ts_bindings_match_the_rust_types() {
    let want = generated();
    if std::env::var_os("FREEWHEEL_WRITE_TS").is_some() {
        std::fs::write(bindings_path(), &want).unwrap();
    }
    let have = std::fs::read_to_string(bindings_path()).unwrap_or_default();
    assert!(
        have == want,
        "src/bindings.ts drifted from the Rust types; regenerate it with \
         FREEWHEEL_WRITE_TS=1 cargo test -p freewheel-core ts_bindings\n{want}"
    );
}
